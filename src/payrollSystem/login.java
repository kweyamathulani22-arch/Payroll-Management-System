    // checks the email and password and opens the menu if they are correct
    private void doLogin() {
        // get what the user typed
        String mail = email.getText().trim();                 // trim removes spaces at the start and end
        String pass = new String(passwordField.getPassword()); // getPassword gives a char array
        // both boxes must be filled in
        if (mail.isEmpty() || pass.isEmpty()) {
            Util.error(this, "Please enter your email and password.");
            return;
        }
        // look for the user with this email (the ? is filled in below, this stops SQL injection)
        String sql = "SELECT user_id, full_name, password_salt, password_hash FROM users WHERE email = ?";
        try (Connection con = Database.getConnection(); PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, mail);
            try (ResultSet rs = ps.executeQuery()) {
                // rs.next() is true if a user was found, then we compare the password hashes
                if (rs.next() && PasswordUtil.matches(pass, rs.getString("password_salt"), rs.getString("password_hash"))) {
                    // remember who is logged in, every screen uses this to only show this user's data
                    Database.currentUserId = rs.getInt("user_id");
                    Database.currentUserName = rs.getString("full_name");
                    // load the settings once so the currency symbol is ready
                    try {
                        Database.loadSettings();
                    } catch (SQLException ex) {
                        // not a problem, the settings are read again when they are needed
                    }
                    new Menu().setVisible(true);
                    dispose();
                } else {
                    // do not say which one was wrong (safer)
                    Util.error(this, "Incorrect email or password.");
                    passwordField.setText("");
                }
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
    }

