    private String savedSignature = "";  // remembers what was saved, so we notice if the user changes it later

    // sets up the form: result boxes cannot be typed in, and puts sensible starting values
    private void prepareForm() {
        javax.swing.JTextField[] readOnly = {jTextField2, payrollMonth2, normalPay, overtimePay,
            grossPay, totalDeduction, netpay};
        for (javax.swing.JTextField box : readOnly) {
            box.setEditable(false);
        }
        // start with the current month and year
        java.time.LocalDate today = java.time.LocalDate.now();
        payrollMonth3.setText(String.valueOf(today.getMonthValue()));
        payrollMonth.setText(String.valueOf(today.getYear()));
        overtimeWorked.setText("0");
        totalDeduction.setText("0.00");
        // hours per month and overtime multiplier come from the Settings screen
        try {
            Database.Settings s = Database.loadSettings();
            normalHoursWorked.setText(Util.plain(s.hoursMonth));
            overtimeRate.setText(Util.plain(s.multiplier));
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
        // when the user clicks in the Amount box the word "Amount" is selected, so typing replaces it
        amountTextFiels.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent e) {
                amountTextFiels.selectAll();
            }
        });
    }

    // finds the employee typed in "Search Employee" (an ID or part of a name)
    private void lookUpEmployee() {
        String text = serachEmployee.getText().trim();
        if (text.isEmpty()) {
            Util.error(this, "Type an employee ID or name first, then press Enter.");
            return;
        }
        try {
            Database.EmployeeInfo found = Database.chooseEmployee(this, text, true);
            if (found == null) {
                Util.error(this, "No active employee found for \"" + text + "\".");
                return;
            }
            // remember the employee and show the details in the boxes
            selected = found;
            jTextField2.setText(found.name + " (" + found.department + ")");
            payrollMonth2.setText(Util.plain(found.rate));
            savedPayrollId = -1;
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
    }

    // adds the typed deduction (description + amount) to the list
    private void addDeductionToList() {
        String description = manulEntDeductions.getText().trim();
        if (description.isEmpty() || description.length() > 100) {
            Util.error(this, "Type what the deduction is for (up to 100 characters), e.g. PAYE tax.");
            return;
        }
        BigDecimal amount;
        try {
            amount = Util.parseDecimal(amountTextFiels.getText()).setScale(2, RoundingMode.HALF_UP);
        } catch (NumberFormatException ex) {
            Util.error(this, "The deduction amount must be a number, e.g. 250.00");
            return;
        }
        if (amount.compareTo(BigDecimal.ZERO) <= 0 || amount.compareTo(new BigDecimal("1000000")) > 0) {
            Util.error(this, "The deduction amount must be more than 0 and not more than 1 000 000.");
            return;
        }
        // keep it in the two lists and clear the boxes for the next one
        dedNames.add(description);
        dedAmounts.add(amount);
        manulEntDeductions.setText("");
        amountTextFiels.setText("Amount");
        refreshDeductionTotal();
        manulEntDeductions.requestFocusInWindow();
    }

    // adds up the deductions and shows the total (hover the mouse over the box to see each one)
    private void refreshDeductionTotal() {
        BigDecimal total = BigDecimal.ZERO;
        StringBuilder tip = new StringBuilder("<html>");
        for (int i = 0; i < dedAmounts.size(); i++) {
            total = total.add(dedAmounts.get(i));
            tip.append(Util.html(dedNames.get(i))).append(": ").append(Util.money(dedAmounts.get(i))).append("<br>");
        }
        totalDeduction.setText(Util.plain(total));
        totalDeduction.setToolTipText(dedNames.isEmpty() ? null : tip.append("</html>").toString());
    }

    // checks all the inputs and fills the Calculation Summary. Gives false if something is wrong.
    private boolean calculate() {
        if (selected == null) {
            Util.error(this, "Search for an employee first (type an ID or name and press Enter).");
            return false;
        }
        // a deduction that was typed but not added would be forgotten, so warn
        if (!manulEntDeductions.getText().trim().isEmpty()) {
            Util.error(this, "You typed a deduction but did not add it. Click \"Add deduction\" or clear the box.");
            return false;
        }
        int month = Util.parseMonth(payrollMonth3.getText());
        if (month < 1) {
            Util.error(this, "Payroll month must be 1-12 or a month name, e.g. September.");
            return false;
        }
        int year;
        try {
            year = Integer.parseInt(payrollMonth.getText().trim());
        } catch (NumberFormatException ex) {
            year = 0;
        }
        if (year < 2000 || year > 2100) {
            Util.error(this, "Payroll year must be a year between 2000 and 2100.");
            return false;
        }
        BigDecimal normalHours;
        BigDecimal overtimeHours;
        BigDecimal multiplier;
        try {
            normalHours = Util.parseDecimal(normalHoursWorked.getText()).setScale(2, RoundingMode.HALF_UP);
            overtimeHours = Util.parseDecimal(overtimeWorked.getText()).setScale(2, RoundingMode.HALF_UP);
            multiplier = Util.parseDecimal(overtimeRate.getText()).setScale(2, RoundingMode.HALF_UP);
        } catch (NumberFormatException ex) {
            Util.error(this, "Hours worked and the overtime rate must be numbers.");
            return false;
        }
        // a month has at most 31 x 24 = 744 hours
        if (normalHours.signum() < 0 || overtimeHours.signum() < 0
                || normalHours.add(overtimeHours).compareTo(new BigDecimal("744")) > 0) {
            Util.error(this, "Hours cannot be negative, and normal + overtime cannot be more than 744 in a month.");
            return false;
        }
        if (multiplier.compareTo(BigDecimal.ONE) < 0 || multiplier.compareTo(new BigDecimal("5")) > 0) {
            Util.error(this, "The overtime rate is a multiplier between 1 and 5 (for example 1.5).");
            return false;
        }

        // the calculation (BigDecimal is used for money so there are no rounding mistakes)
        BigDecimal rate = selected.rate;
        BigDecimal normal = rate.multiply(normalHours).setScale(2, RoundingMode.HALF_UP);
        BigDecimal overtime = rate.multiply(multiplier).multiply(overtimeHours).setScale(2, RoundingMode.HALF_UP);
        BigDecimal gross = normal.add(overtime);
        BigDecimal deductions = BigDecimal.ZERO;
        for (BigDecimal d : dedAmounts) {
            deductions = deductions.add(d);
        }
        BigDecimal net = gross.subtract(deductions);
        if (net.signum() < 0) {
            Util.error(this, "The deductions (" + Util.money(deductions) + ") are more than the gross pay ("
                    + Util.money(gross) + ").");
            return false;
        }

        // keep the results (the save method uses them) and show them
        calcMonth = month;
        calcYear = year;
        calcNormalHours = normalHours;
        calcOvertimeHours = overtimeHours;
        calcMultiplier = multiplier;
        calcNormalPay = normal;
        calcOvertimePay = overtime;
        calcGross = gross;
        calcDeductions = deductions;
        calcNet = net;
        normalPay.setText(Util.plain(normal));
        overtimePay.setText(Util.plain(overtime));
        grossPay.setText(Util.plain(gross));
        totalDeduction.setText(Util.plain(deductions));
        netpay.setText(Util.plain(net));
        return true;
    }

    // a text that describes exactly what is on the screen, used to see if it was saved already
    private String signature() {
        return selected.id + "|" + calcYear + "|" + calcMonth + "|" + calcNormalHours + "|" + calcOvertimeHours
                + "|" + calcMultiplier + "|" + dedNames + dedAmounts;
    }

    // saves the payroll record and its deductions (all or nothing, using a transaction)
    private boolean savePayroll() {
        if (!calculate()) {
            return false;
        }
        try (Connection con = Database.getConnection()) {
            con.setAutoCommit(false);
            try {
                // 1. is there already a payroll for this employee and month?
                int existing = -1;
                try (PreparedStatement ps = con.prepareStatement("SELECT payroll_id FROM payroll_records "
                        + "WHERE owner_id = ? AND employee_id = ? AND pay_year = ? AND pay_month = ?")) {
                    ps.setInt(1, Database.currentUserId);
                    ps.setInt(2, selected.id);
                    ps.setInt(3, calcYear);
                    ps.setInt(4, calcMonth);
                    try (ResultSet rs = ps.executeQuery()) {
                        if (rs.next()) {
                            existing = rs.getInt(1);
                        }
                    }
                }
                // if yes, ask if it must be replaced (the old deductions and payslip are deleted too)
                if (existing > 0) {
                    if (!Util.confirm(this, "Payroll for " + selected.name + " for " + Util.monthName(calcMonth) + " "
                            + calcYear + " already exists.\nReplace it with these figures? (Its payslip is replaced too.)")) {
                        con.rollback();
                        return false;
                    }
                    try (PreparedStatement ps = con.prepareStatement(
                            "DELETE FROM payroll_records WHERE payroll_id = ? AND owner_id = ?")) {
                        ps.setInt(1, existing);
                        ps.setInt(2, Database.currentUserId);
                        ps.executeUpdate();
                    }
                }
                // 2. save the payroll record
                int payrollId;
                String sql = "INSERT INTO payroll_records (owner_id, employee_id, pay_year, pay_month, hourly_rate, "
                        + "normal_hours, overtime_hours, overtime_multiplier, normal_pay, overtime_pay, gross_pay, "
                        + "total_deductions, net_pay) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";
                try (PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                    ps.setInt(1, Database.currentUserId);
                    ps.setInt(2, selected.id);
                    ps.setInt(3, calcYear);
                    ps.setInt(4, calcMonth);
                    ps.setBigDecimal(5, selected.rate);
                    ps.setBigDecimal(6, calcNormalHours);
                    ps.setBigDecimal(7, calcOvertimeHours);
                    ps.setBigDecimal(8, calcMultiplier);
                    ps.setBigDecimal(9, calcNormalPay);
                    ps.setBigDecimal(10, calcOvertimePay);
                    ps.setBigDecimal(11, calcGross);
                    ps.setBigDecimal(12, calcDeductions);
                    ps.setBigDecimal(13, calcNet);
                    ps.executeUpdate();
                    // get the id of the new record
                    try (ResultSet keys = ps.getGeneratedKeys()) {
                        keys.next();
                        payrollId = keys.getInt(1);
                    }
                }
                // 3. save every deduction (addBatch collects them and executeBatch saves them together)
                try (PreparedStatement ps = con.prepareStatement("INSERT INTO payroll_deductions "
                        + "(owner_id, payroll_id, description, amount) VALUES (?, ?, ?, ?)")) {
                    for (int i = 0; i < dedNames.size(); i++) {
                        ps.setInt(1, Database.currentUserId);
                        ps.setInt(2, payrollId);
                        ps.setString(3, dedNames.get(i));
                        ps.setBigDecimal(4, dedAmounts.get(i));
                        ps.addBatch();
                    }
                    ps.executeBatch();
                }
                con.commit();   // everything worked, make it permanent
                savedPayrollId = payrollId;
                savedSignature = signature();
                return true;
            } catch (SQLException ex) {
                con.rollback();   // something failed, undo
                throw ex;
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
            return false;
        }
    }

    // saves the payroll if needed, makes the payslip record and shows the payslip window
    private void makePayslip() {
        if (!calculate()) {
            return;
        }
        // the company name and address are printed on the payslip, so they must be filled in
        try {
            Database.Settings s = Database.loadSettings();
            if (s.companyName.isEmpty() || s.companyAddress.isEmpty()) {
                Util.error(this, "Please type your company name and address in Settings first.\n"
                        + "They are printed at the top of every payslip.");
                return;
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
            return;
        }
        // save first if it was not saved, or if the user changed something after saving
        if (savedPayrollId < 0 || !signature().equals(savedSignature)) {
            if (!Util.confirm(this, "This payroll is not saved yet (or was changed after saving).\n"
                    + "Save it now and generate the payslip?")) {
                return;
            }
            if (!savePayroll()) {
                return;
            }
        }
        try (Connection con = Database.getConnection()) {
            int payslipId = -1;
            // does this payroll record already have a payslip?
            try (PreparedStatement ps = con.prepareStatement(
                    "SELECT payslip_id FROM payslips WHERE payroll_id = ? AND owner_id = ?")) {
                ps.setInt(1, savedPayrollId);
                ps.setInt(2, Database.currentUserId);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        payslipId = rs.getInt(1);
                    }
                }
            }
            if (payslipId > 0) {
                // yes: only update the date it was generated
                try (PreparedStatement ps = con.prepareStatement(
                        "UPDATE payslips SET generated_at = CURRENT_TIMESTAMP WHERE payslip_id = ? AND owner_id = ?")) {
                    ps.setInt(1, payslipId);
                    ps.setInt(2, Database.currentUserId);
                    ps.executeUpdate();
                }
            } else {
                // no: make a new one. The number is my highest payslip number + 1 (every user counts from 1)
                try (PreparedStatement ps = con.prepareStatement(
                        "INSERT INTO payslips (owner_id, payslip_number, payroll_id) "
                        + "SELECT ?, COALESCE(MAX(payslip_number), 0) + 1, ? FROM payslips WHERE owner_id = ?",
                        Statement.RETURN_GENERATED_KEYS)) {
                    ps.setInt(1, Database.currentUserId);
                    ps.setInt(2, savedPayrollId);
                    ps.setInt(3, Database.currentUserId);
                    ps.executeUpdate();
                    try (ResultSet keys = ps.getGeneratedKeys()) {
                        keys.next();
                        payslipId = keys.getInt(1);
                    }
                }
            }
            // show the payslip in its own window (it has a Print button)
            Util.showPayslip(this, Database.buildPayslipHtml(payslipId));
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
    }

