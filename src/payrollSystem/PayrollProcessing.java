    private Database.EmployeeInfo selected;                                  // the employee we are working on
    private final java.util.List<String> dedNames = new java.util.ArrayList<>();       // deduction descriptions
    private final java.util.List<BigDecimal> dedAmounts = new java.util.ArrayList<>(); // deduction amounts
    // the values of the last calculation
    private BigDecimal calcNormalHours, calcOvertimeHours, calcMultiplier;
    private BigDecimal calcNormalPay, calcOvertimePay, calcGross, calcDeductions, calcNet;
    private int calcMonth, calcYear;
