    // the database id of each table row (same order as the rows), used when a row is double-clicked
    private final java.util.List<Integer> payslipIds = new java.util.ArrayList<>();

    // fills the table with MY payslips, newest first
    private void loadPayslips() {
        payslipIds.clear();
        DefaultTableModel model = new DefaultTableModel(
                new String[] {"Payslip No.", "Employee", "ID", "Pay Period ", "Gross", "Deductions"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        String sql = "SELECT payslip_id, payslip_label, employee_name, employee_id, pay_period, gross_pay, "
                + "total_deductions FROM v_payslip_list WHERE owner_id = ? ORDER BY payslip_number DESC";
        try (Connection con = Database.getConnection(); PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, Database.currentUserId);   // only MY payslips
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    payslipIds.add(rs.getInt(1));
                    model.addRow(new Object[] {rs.getString(2), rs.getString(3), String.valueOf(rs.getInt(4)),
                        Util.shortPeriod(rs.getString(5)), Util.money(rs.getBigDecimal(6)), Util.money(rs.getBigDecimal(7))});
                }
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
        payslipTable.setModel(model);
        Util.setColumnWidths(payslipTable, 85, 150, 50, 90, 100, 100);
    }

