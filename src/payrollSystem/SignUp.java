    // checks the form and creates the account (fullName1 is the Full Name box, fullName is the Email box)
    private void register() {
        // get what the user typed
        String name = fullName1.getText().trim();
        String mail = fullName.getText().trim();
        String pass = new String(passwordSignUp.getPassword());
        String confirm = new String(passwordConfirm.getPassword());

        // check every box before touching the database
        if (name.length() < 2 || name.length() > 100) {
            Util.error(this, "Please enter your full name.");
            return;
        }
        if (!Util.isEmail(mail) || mail.length() > 120) {
            Util.error(this, "Please enter a valid email address.");
            return;
        }
        if (pass.length() < 8) {
            Util.error(this, "The password must be at least 8 characters long.");
            return;
        }
        if (!pass.equals(confirm)) {
            Util.error(this, "The two passwords do not match.");
            return;
        }

        // never save the real password, only the salt and the hash
        String salt = PasswordUtil.newSalt();
        try (Connection con = Database.getConnection()) {
            con.setAutoCommit(false);   // the user and the settings row are saved together or not at all
            try {
                int newUserId;
                try (PreparedStatement ps = con.prepareStatement(
                        "INSERT INTO users (full_name, email, password_salt, password_hash) VALUES (?, ?, ?, ?)",
                        Statement.RETURN_GENERATED_KEYS)) {
                    ps.setString(1, name);
                    ps.setString(2, mail);
                    ps.setString(3, salt);
                    ps.setString(4, PasswordUtil.hash(salt, pass));
                    ps.executeUpdate();
                    // get the id MySQL gave to the new user
                    try (ResultSet keys = ps.getGeneratedKeys()) {
                        keys.next();
                        newUserId = keys.getInt(1);
                    }
                }
                // every user gets their own (empty) company settings
                try (PreparedStatement ps = con.prepareStatement("INSERT INTO company_settings (owner_id) VALUES (?)")) {
                    ps.setInt(1, newUserId);
                    ps.executeUpdate();
                }
                con.commit();
            } catch (SQLException ex) {
                con.rollback();   // something went wrong, undo everything
                throw ex;
            }
            Util.info(this, "Account created. You can now sign in.");
            new login().setVisible(true);
            dispose();
        } catch (SQLException ex) {
            // error code 1062 = duplicate value, so the email is already used
            if (ex.getErrorCode() == 1062) {
                Util.error(this, "An account with this email address already exists.");
            } else {
                Util.dbError(this, ex);
            }
        }
    }

