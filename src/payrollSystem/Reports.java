    // makes a table model whose cells cannot be edited
    private static DefaultTableModel readOnlyModel(String[] columns) {
        return new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    // top table: every employee paid in my latest payroll month, and the three totals under it
    private void loadMonthly() {
        DefaultTableModel model = readOnlyModel(
                new String[] {"Employee", "Department", "Period", "Gross", "Deductions", "Net"});
        BigDecimal gross = BigDecimal.ZERO;
        BigDecimal deductions = BigDecimal.ZERO;
        BigDecimal net = BigDecimal.ZERO;
        try (Connection con = Database.getConnection()) {
            // find my latest payroll month
            int year = 0;
            int month = 0;
            try (PreparedStatement ps = con.prepareStatement("SELECT pay_year, pay_month FROM payroll_records "
                    + "WHERE owner_id = ? ORDER BY pay_year DESC, pay_month DESC LIMIT 1")) {
                ps.setInt(1, Database.currentUserId);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        year = rs.getInt(1);
                        month = rs.getInt(2);
                    }
                }
            }
            // if there is one, list its records and add up the totals
            if (year > 0) {
                jLabel2.setText("Monthly Payroll Summary - " + Util.monthName(month) + " " + year);
                try (PreparedStatement ps = con.prepareStatement("SELECT employee_name, department, pay_period, "
                        + "gross_pay, total_deductions, net_pay FROM v_payroll_detail "
                        + "WHERE owner_id = ? AND pay_year = ? AND pay_month = ? ORDER BY employee_name")) {
                    ps.setInt(1, Database.currentUserId);
                    ps.setInt(2, year);
                    ps.setInt(3, month);
                    try (ResultSet rs = ps.executeQuery()) {
                        while (rs.next()) {
                            gross = gross.add(rs.getBigDecimal(4));
                            deductions = deductions.add(rs.getBigDecimal(5));
                            net = net.add(rs.getBigDecimal(6));
                            model.addRow(new Object[] {rs.getString(1), rs.getString(2), Util.shortPeriod(rs.getString(3)),
                                Util.money(rs.getBigDecimal(4)), Util.money(rs.getBigDecimal(5)),
                                Util.money(rs.getBigDecimal(6))});
                        }
                    }
                }
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
        monthlyPayrollTable.setModel(model);
        Util.setColumnWidths(monthlyPayrollTable, 115, 70, 95, 100, 95, 100);
        GrossTotal.setText(Util.money(gross));
        deductionsTotal.setText(Util.money(deductions));
        netTotals.setText(Util.money(net));
    }

    // finds the employee typed in the search box and shows the history of that employee
    private void searchIndividual() {
        String text = individualSearchField.getText().trim();
        if (text.isEmpty()) {
            loadIndividual(null);
            return;
        }
        try {
            Database.EmployeeInfo found = Database.chooseEmployee(this, text, false);
            if (found == null) {
                Util.error(this, "No employee found for \"" + text + "\".");
                return;
            }
            loadIndividual(found);
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        }
    }

    // bottom table: the payroll history of one employee (empty until somebody is searched)
    private void loadIndividual(Database.EmployeeInfo who) {
        DefaultTableModel model = readOnlyModel(
                new String[] {"Period", "Normal Hour", "Overtime", "Gross", "Deductions", "Net"});
        if (who == null) {
            jLabel4.setText("Indvidual Payroll History");
        } else {
            jLabel4.setText("Indvidual Payroll History - " + who.name);
            try (Connection con = Database.getConnection();
                 PreparedStatement ps = con.prepareStatement("SELECT pay_period, normal_hours, overtime_hours, "
                         + "gross_pay, total_deductions, net_pay FROM v_payroll_detail "
                         + "WHERE owner_id = ? AND employee_id = ? ORDER BY pay_year DESC, pay_month DESC")) {
                ps.setInt(1, Database.currentUserId);
                ps.setInt(2, who.id);
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        model.addRow(new Object[] {Util.shortPeriod(rs.getString(1)), Util.plain(rs.getBigDecimal(2)),
                            Util.plain(rs.getBigDecimal(3)), Util.money(rs.getBigDecimal(4)),
                            Util.money(rs.getBigDecimal(5)), Util.money(rs.getBigDecimal(6))});
                    }
                }
            } catch (SQLException ex) {
                Util.dbError(this, ex);
            }
        }
        individualPayrollTable.setModel(model);
        Util.setColumnWidths(individualPayrollTable, 95, 90, 70, 100, 95, 100);
    }

    // Runs a query (it must have one ? for my user id) and saves the result in a CSV file that opens in Excel
    private void exportToCsv(String sql, String suggestedName) {
        // let the user choose where to save the file
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Save as CSV");
        chooser.setSelectedFile(new File(suggestedName));
        if (chooser.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        File file = chooser.getSelectedFile();
        if (file.exists() && !Util.confirm(this, file.getName() + " already exists. Replace it?")) {
            return;
        }
        try (Connection con = Database.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, Database.currentUserId);   // only MY records are exported
            try (ResultSet rs = ps.executeQuery();
                 Writer out = new OutputStreamWriter(new FileOutputStream(file), StandardCharsets.UTF_8)) {
                out.write('\uFEFF');   // this mark lets Excel read the file as UTF-8
                // first line: the column names
                ResultSetMetaData meta = rs.getMetaData();
                int columns = meta.getColumnCount();
                for (int c = 1; c <= columns; c++) {
                    out.write(Util.csv(meta.getColumnLabel(c)) + (c < columns ? "," : "\r\n"));
                }
                // then one line for every record
                int rows = 0;
                while (rs.next()) {
                    for (int c = 1; c <= columns; c++) {
                        out.write(Util.csv(rs.getString(c)) + (c < columns ? "," : "\r\n"));
                    }
                    rows++;
                }
                Util.info(this, rows + " record(s) saved to:\n" + file.getAbsolutePath());
            }
        } catch (SQLException ex) {
            Util.dbError(this, ex);
        } catch (IOException ex) {
            Util.error(this, "The file could not be written:\n" + ex.getMessage());
        }
    }

